#!/usr/bin/env node
/**
 * Exports the Nyro figure to the site. Run from the project root after any
 * change to figures/nyro.js:
 *
 *   node figures/export.mjs
 *
 * 1. Writes app/vendor/hairline/nyro.js: the same figure code as an ES module
 *    (`import HL from "./kernel.js"` on top, `export const nyro = { … }` in
 *    place of the bench's `hairline({ … })` call). Nothing else changes.
 * 2. Builds figures/hairline-nyro.html with the skill's build.mjs, opens it in
 *    Chrome, waits for the stack to settle, and writes
 *    app/components/hairline/nyro-rest.ts: the rest pose's svg markup and the
 *    kernel's stylesheet, so the prerendered page shows exactly what the live
 *    figure draws first.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { chromium } from "@playwright/test";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skill = process.env.HAIRLINE_SKILL ?? join(process.env.USERPROFILE ?? process.env.HOME ?? "", ".agents/skills/hairline-create");
const src = readFileSync(join(root, "figures/nyro.js"), "utf8").replace(/\r\n/g, "\n");

// 1. the ES module
const destructure = /\nconst \{[\s\S]*?\} = HL;\n/;
const declare = /\nhairline\(\{([\s\S]*)\}\);\s*$/;
if (!destructure.test(src) || !declare.test(src)) throw new Error("figures/nyro.js no longer has the shape this script expects.");
const esm = src
  .replace(destructure, (m) => `\nimport HL from "./kernel.js";\n${m}`)
  .replace(declare, (_m, body) => `\nexport const nyro = Object.freeze({${body}});\n`);
const banner = "/* Generated by figures/export.mjs from figures/nyro.js. Edit the source, then run it again. */\n";
writeFileSync(join(root, "app/vendor/hairline/nyro.js"), banner + esm);

// 2. the rest pose, as the browser draws it
const page = join(root, "figures/hairline-nyro.html");
execFileSync(process.execPath, [join(skill, "build.mjs"), "nyro.js"], { cwd: join(root, "figures"), stdio: "inherit" });
const browser = await chromium.launch({ channel: process.env.HAIRLINE_CHANNEL ?? "chrome" });
try {
  const tab = await browser.newPage({ viewport: { width: 900, height: 900 }, reducedMotion: "no-preference" });
  // Keep a hold of the figure the bench is given, to mount a second copy below.
  await tab.addInitScript(() => {
    let bench;
    Object.defineProperty(window, "hairline", {
      configurable: true,
      get: () => bench,
      set: (fn) => { bench = (figure) => { window.__figure = figure; return fn(figure); }; },
    });
  });
  await tab.goto(pathToFileURL(page).href);
  await tab.waitForTimeout(2000);
  const { markup, css, read, open } = await tab.evaluate(() => {
    const restSvg = document.querySelector("#stage > svg");
    // A second copy, mounted with its entrance: its first frame, drawn in register(), is the open pose.
    const stage = document.createElement("div"), svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("viewBox", "0 0 400 320");
    stage.append(svg);
    document.body.append(stage);
    const sink = { textContent: "" };
    const handle = window.__figure.mount({ stage, svg, read: sink }, window.__figure.range[1]);
    const firstY = (root) => [...root.querySelectorAll(":scope > g > g")].map((grp) => Number(/^M[-\d.]+ ([-\d.]+)/.exec(grp.lastElementChild.getAttribute("d"))[1]));
    const rest = firstY(restSvg), opened = firstY(svg);
    handle.destroy();
    stage.remove();
    return {
      markup: restSvg.innerHTML,
      css: window.HL.css(false),
      read: document.getElementById("read").textContent,
      open: opened.map((y, i) => Math.round((y - rest[i]) * 100) / 100),
    };
  });
  if (read !== "rest") throw new Error(`the figure is not at rest (read-out "${read}")`);
  // The entrance, as CSS on the static copy: each plate starts where the live figure would start it,
  // and lands on the kernel's discrete clock (700ms on .32,.72,0,1), the figure's stagger apart, top first.
  const step = Number(/\bSTEP = (\d+)/.exec(src)?.[1] ?? 40), last = open.length - 1;
  const enterCss = open.map((dy, i) => dy ? `@keyframes hl-nyro-l${i}{from{transform:translate3d(0,${dy}px,0)}}` : "").join("")
    + "@media (prefers-reduced-motion:no-preference){"
    + open.map((dy, i) => dy ? `.hl-nyro-enter>g>g:nth-child(${i + 1}){animation:hl-nyro-l${i} 700ms cubic-bezier(.32,.72,0,1) ${(last - i) * step}ms backwards}` : "").join("")
    + "}";
  const out = `/* Generated by figures/export.mjs: the Nyro figure at rest, captured in Chrome. Do not edit. */

/** The inner markup of the figure's svg (viewBox 0 0 400 320) in its rest pose. */
export const NYRO_REST_SVG = ${JSON.stringify(markup)};

/** The Hairline kernel's stylesheet, HL.css(false), so the static copy is styled before the kernel loads. */
export const HAIRLINE_KERNEL_CSS = ${JSON.stringify(css)};

/**
 * The entrance, played by CSS on the static copy (wrapped in <g class="hl-nyro-enter">), so it
 * starts with the first paint and needs no JavaScript: the plates settle from the live figure's
 * open pose (${JSON.stringify(open)} viewBox units) to rest. Off under prefers-reduced-motion.
 */
export const NYRO_ENTER_CSS = ${JSON.stringify(enterCss)};
`;
  writeFileSync(join(root, "app/components/hairline/nyro-rest.ts"), out);
  console.log(`nyro-rest.ts: ${markup.length} characters of rest markup, ${css.length} of css, entrance ${JSON.stringify(open)}`);
} finally {
  await browser.close();
}
